    /**
     * 같은 사람·같은 날·같은 위치를 고르면 하루 종일 같은 카드가 나와요.
     * @param pick 0~2 (사용자가 고른 카드 위치)
     */
    fun draw(personKey: String, date: LocalDate, pick: Int): Draw {
        val seed = (personKey.hashCode().toLong() * 31 + date.toEpochDay()) * 7 + pick * 13
        val rnd = java.util.Random(seed)
        val card = cards[rnd.nextInt(cards.size)]
        val reversed = rnd.nextInt(100) < 25
        return Draw(card, reversed)
    }
